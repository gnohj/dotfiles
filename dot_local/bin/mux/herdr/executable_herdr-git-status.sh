#!/usr/bin/env bash
# herdr-git-status.sh — colour each open herdr workspace's NAME by its AGENT state, using the SAME
# gitmux.yml as the tmux status line + the ctrl+t picker for the working-tree read. There is no
# glyph any more: the name itself carries the colour, and a dirty tree is a trailing * on it.
# That means replacing the built-in `workspace` token with $ws plus a $ws_<state> pair, since herdr
# styles a token by one flat inline fg and has no state-varying form (skills/herdr-upgrade/
# watchlist.md item 2). Wired in dot_config/herdr/config.toml ([ui.sidebar.spaces]).
#
# The same pass also writes the ctrl+t picker's status cache (herdr_gitmux.update),
# so the picker's column and this sidebar token come from ONE gitmux run per repo and
# can't disagree. Without it the picker showed whatever its last open had computed,
# i.e. arbitrarily stale; now open workspaces are at most $INTERVAL seconds behind.
#
#   herdr-git-status.sh          one refresh pass over every open workspace
#   herdr-git-status.sh --loop   daemon: refresh every $INTERVAL s (flock = one only)
#   herdr-git-status.sh --kick   refresh once now, then ensure the --loop daemon is up
#
# Everything runs through the herdr CLI (socket API), so it works local AND over
# `herdr --remote` — the poller lives on whichever host runs the herdr server, the
# same host the repos live on. gitmux SYMBOLS only (its branch field is dropped - it carries a
# glyph and its own coloring, and `$br` below asks git directly); tmux "#[…]" color codes are
# stripped since a metadata token renders as plain theme-colored text.
#
# A third pass clears the per-PANE `$pbr`/`$pgit`: agent rows never carry a checkout's state.
#
# The same pass feeds `$br`/`$br_on`, the sidebar's second row. These REPLACE herdr's built-in
# `branch` token, which can only render the branch verbatim: a ticket worktree already spells
# its key out on row 1, so row 2 carries the branch with that key stripped
# (IHRWEB-24314-listen-endpoint -> listen-endpoint). Two tokens rather than one because a
# custom token takes a single unconditional fg, losing the mauve/overlay0 focus split the
# built-in gets for free (skills/herdr-upgrade/watchlist.md item 2). Exactly one of the pair
# ever holds the text: herdr-focus-tracker.py::paint_branch moves it on workspace.focused, and
# this pass picks the same slot from `focused` so an 8s poll never drags the accent back.
set -uo pipefail

herdr="${HERDR_BIN_PATH:-herdr}"
. "$HOME/.local/bin/mux/shared/mux-env.sh"
export HERDR_BIN_PATH="$herdr"

GITMUX_CFG="$HOME/.config/gitmux/gitmux.yml"
SCRIPTS_DIR="$HOME/.local/bin/mux/herdr"
INTERVAL="${HERDR_GIT_INTERVAL:-8}"
export TTL_MS=$(( (INTERVAL + 30) * 1000 ))   # outlive a couple of missed passes
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/herdr"
LOCK="$STATE_DIR/git-status.lock"
# Bracketed first char: the regex text itself never contains the string it matches, so a
# shell whose command line mentions this pattern (an admin typing pgrep/pkill, a wrapper)
# can never be matched — and killed — as if it were the daemon.
LOOP_RE="[h]erdr-git-status[.]sh --loop"

refresh_once() {
  command -v jq >/dev/null 2>&1 || return 0
  command -v python3 >/dev/null 2>&1 || return 0
  command -v gitmux >/dev/null 2>&1 || return 0
  GITMUX_CFG="$GITMUX_CFG" SCRIPTS_DIR="$SCRIPTS_DIR" python3 - <<'PY'
import os, json, re, subprocess, sys, time

sys.dont_write_bytecode = True             # no __pycache__ in the deployed scripts dir
sys.path.insert(0, os.environ.get("SCRIPTS_DIR", os.path.expanduser("~/.local/bin/mux/herdr")))
try:
    import herdr_gitmux as hg              # shared with herdr-sesh.sh — see its docstring
    from herdr_label import row_indent, is_pin, wants_branch  # shared with thread-status + sysinfo, so the writers cannot drift
except Exception:
    sys.exit(0)                            # mid-apply window; the next pass picks it up

HERDR = os.environ.get("HERDR_BIN_PATH", "herdr")
# Kept in step with gitmux.yml (generated by colorscheme-set). ● staged, ✖ conflict,
# ✚ modified, 󱀶 untracked. NOT the stash or the insertion/deletion glyphs.
# Conflict counts as unstaged: a conflicted path is not work that is ready to commit.
STAGED_SIGN = "●"
UNSTAGED_SIGNS = ("✖", "✚", "\U000f1036")
DIRTY_SIGNS = (STAGED_SIGN,) + UNSTAGED_SIGNS
# gitmux's ahead/behind markers, the same pair herdr-sysinfo.py counts for $sync.
SYNC_SIGNS = ("\U0001f446", "\U0001f447")
# Suffix IS the colour, so a remap is a slot move here; unknown stays bare on `ws` for herdr's own text/subtext0. Mirror of MARK_BY_STATUS in herdr-agent-activity.py.
CFG = os.environ.get("GITMUX_CFG", os.path.expanduser("~/.config/gitmux/gitmux.yml"))
TTL = os.environ.get("TTL_MS", "60000")

def out(args, cwd=None):
    try:
        return subprocess.run(args, cwd=cwd, capture_output=True, text=True, timeout=4).stdout
    except Exception:
        return ""

# Ticket key stripped off the front, because row 1 of the sidebar already ends in it
# (herdr-sesh-layout.sh labels a bucketed ticket worktree web/infra/IHRWEB-24314). master,
# untick/foo and every other unprefixed branch pass through whole. Detached HEAD has no branch
# name, so it falls back to the short sha rather than leaving the row blank.
TICKET_PREFIX = re.compile(r"^[A-Z]+-[0-9]+-")
_BRANCH = {}

def raw_branch(cwd):
    if cwd not in _BRANCH:
        name = out(["git", "-C", cwd, "branch", "--show-current"]).strip()
        _BRANCH[cwd] = name or out(["git", "-C", cwd, "rev-parse", "--short", "HEAD"]).strip()
    return _BRANCH[cwd]

# firstmate's owner segment (fm/) names the owner of a workspace you are already inside, so it goes; lookahead keeps an ordinary feature/foo whole.
OWNER_PREFIX = re.compile(r"^[a-z][A-Za-z0-9_.-]*/(?=[A-Z]+-)")

_DEFAULT_BRANCH = {}

def default_branch(cwd):
    """The repo's default branch via origin/HEAD, or "" when there is no remote to ask."""
    root = ident(cwd)[1] or cwd
    if root not in _DEFAULT_BRANCH:
        ref = out(["git", "-C", cwd, "symbolic-ref", "--short", "refs/remotes/origin/HEAD"]).strip()
        _DEFAULT_BRANCH[root] = ref.split("/", 1)[1] if "/" in ref else ref
    return _DEFAULT_BRANCH[root]

def detached_head(cwd):
    """Short sha when HEAD is DETACHED, else "".

    raw_branch() collapses branch-or-sha, which is right for identity but wrong for display: a
    detached checkout has to read as detached rather than as a branch that happens to look like a
    sha. Every detached row renders `(<sha>)*`, homes included.
    """
    if out(["git", "-C", cwd, "branch", "--show-current"]).strip():
        return ""
    return out(["git", "-C", cwd, "rev-parse", "--short", "HEAD"]).strip()

def branch(cwd, keep_key=False):
    """Row 2 text: `<line>(<sha>)`, with a trailing `*` when HEAD is detached.

    The sha rides every row because a branch name alone does not say which commit a checkout is
    parked on, and several of these are pinned rather than tracking - a leased secondmate home, a
    treehouse pool slot. A detached checkout names its line only when the sha really is an ancestor
    of it, so an arbitrary one reads `(<sha>)*` rather than claiming a branch it is not on.

    keep_key leaves a projection's ticket key on: its row 1 is a truncated task label, not the clean
    `<repo>/<number>` an ordinary ticket worktree gets, so row 2 there names the branch as created.
    """
    head = out(["git", "-C", cwd, "rev-parse", "--short", "HEAD"]).strip()
    if detached_head(cwd):
        base = default_branch(cwd)
        on_line = bool(base) and subprocess.run(
            ["git", "-C", cwd, "merge-base", "--is-ancestor", "HEAD", f"origin/{base}"],
            capture_output=True).returncode == 0
        return f"{base}({head})*" if on_line else f"({head})*"
    name = raw_branch(cwd)
    if not keep_key:
        name = TICKET_PREFIX.sub("", OWNER_PREFIX.sub("", name)) or name
    return f"{name}({head})" if head else name

# --path-format=absolute is load-bearing: bare --git-common-dir is relative in a checkout, absolute in a worktree.
_IDENT = {}

def ident(cwd):
    """(worktree_root, repo_root) for cwd; ("", "") when it is not a checkout.

    toplevel identifies the WORKTREE, common-dir the REPO, so the pair separates a sibling
    worktree of this repo from another repo entirely. herdr has neither: `workspace list`
    carries no path at all, so every agent row renders its workspace's label wherever it sits.
    """
    if cwd not in _IDENT:
        parts = out(["git", "-C", cwd, "rev-parse", "--path-format=absolute",
                     "--show-toplevel", "--git-common-dir"]).split()
        _IDENT[cwd] = (parts[0], parts[1]) if len(parts) == 2 else ("", "")
    return _IDENT[cwd]

# Sidebar token is ONE glyph: "this tree has uncommitted work", nothing more. The full
# per-class counts stay in the ctrl+t picker and the tmux status line, which have the
# width for them; a 26-col sidebar does not, and the counts were never actionable there.
# DIRTY_SIGNS is the gitmux staged/conflict/modified/untracked set — stash is deliberately
# excluded (stashed work is not uncommitted work in the tree), as are the insertion and
# deletion line counts. Clean tree clears the token, so the row disappears entirely.
# Cached by tree: the pane pass would otherwise re-run gitmux once per pane sitting in it.
_SIGN = {}

def sign(cwd):
    """(dirty, needs_sync, picker_entry) for cwd — ONE gitmux run per tree."""
    if cwd not in _SIGN:
        _br, spairs = hg.parse(hg.run(cwd, CFG))     # branch dropped: herdr shows it already
        flat = hg.plain(spairs)
        dirty = any(s in flat for s in DIRTY_SIGNS)
        needs_sync = any(s in flat for s in SYNC_SIGNS)
        # Same gitmux run feeds the ctrl+t picker's cache, so its column can't disagree
        # with this token. roots_only is moot here: a workspace cwd is asked either way.
        _SIGN[cwd] = (dirty, needs_sync, hg.entry(spairs, now))
    return _SIGN[cwd]

# ONE call for all four tokens, not one per token: a second report from the same --source
# carrying the same --seq is dropped as not-newer, so split calls silently lost whichever
# went second. --token and --clear-token are both repeatable and mix freely.
def report(kind, target, values, ttl=None):
    # Fresh seq PER CALL: same source + same seq is dropped as not-newer, so a workspace needing two calls (names TTL-less, branch not) would lose the second.
    args = [HERDR, kind, "report-metadata", target, "--source", "gitmux", "--seq", str(time.time_ns())]
    if ttl != "":
        args += ["--ttl-ms", ttl or TTL]
    for name, value in values:
        args += ["--token", name + "=" + value] if value else ["--clear-token", name]
    subprocess.run(args, capture_output=True)

try:
    panes = json.loads(out([HERDR, "pane", "list"]))
except Exception:
    sys.exit(0)

# Which space is active decides whether the branch goes in `$br` (dim) or `$br_on` (accent).
# The swap itself is herdr-focus-tracker.py's job, event-driven off workspace.focused; this
# pass only has to agree with it, or every poll would drag the accent back to the wrong space.
try:
    _spaces = json.loads(out([HERDR, "workspace", "list"]))["result"]["workspaces"]
    focused = {w["workspace_id"] for w in _spaces if w.get("focused")}
    ws_label = {w["workspace_id"]: w.get("label") or "" for w in _spaces}
    # herdr's own rolled-up state, the same value the row's state_icon dot uses - never our guess.
    ws_status = {w["workspace_id"]: w.get("agent_status") or "unknown" for w in _spaces}
except Exception:
    focused = set()
    ws_label = {}
    ws_status = {}

def cwd_of(p):
    return (p.get("foreground_cwd") or p.get("cwd") or "").rstrip("/")

# Sorted: first-seen follows `pane list` order, so the baseline below must not depend on which pane that is.
plist = sorted(panes.get("result", {}).get("panes", []),
               key=lambda p: (p.get("workspace_id") or "", p.get("pane_id") or ""))

ws_cwd = {}
for p in plist:
    # Spawn cwd, never the foreground: a pane that cd'd into another worktree must not become the baseline.
    w, c = p.get("workspace_id"), (p.get("cwd") or "").rstrip("/")
    # EXCEPT a firstmate projection (`└ `), which spawns in the read-only clone and works in the task worktree, so its spawn cwd reports the clone's default branch forever - the foreground IS the baseline there, as thread-status already assumes.
    if w and ws_label.get(w, "").startswith("└ "):
        c = (p.get("foreground_cwd") or c or "").rstrip("/")
    if w and c and w not in ws_cwd:
        ws_cwd[w] = c

now = time.time()
picker = {}
# EVERY workspace, not just those with a usable cwd: $ws replaces the built-in `workspace` token, so a row this pass skips loses its NAME, not just its git state.
for w, label in ws_label.items():
    c = ws_cwd.get(w, "")
    dirty = needs_sync = False
    if c and os.path.isdir(c):
        dirty, needs_sync, entry = sign(c)
        picker[c] = entry
    if is_pin(label):
        # Rows below belong to sysinfo. Cleared, not skipped, so a stale branch goes rather than lingering.
        report("workspace", w, (("br", ""), ("br_on", "")))
        continue
    # Branch only where it adds something over row 0 (see wants_branch); a projection duplicates it unless detached, where the checkout is off the line its label implies.
    projected = label.startswith("└ ")
    br = ""
    if c and os.path.isdir(c) and wants_branch(label) and not (projected and not detached_head(c)):
        br = branch(c, keep_key=projected)
    if br:
        br = row_indent(label) + br
    lit = w in focused
    report("workspace", w, (("br", "" if lit else br), ("br_on", br if lit else "")))

# Agent rows never carry a checkout's state (the spaces panel's job), so all four pane tokens are cleared; a pane outside its workspace's worktree still feeds the picker.
for p in plist:
    pid, w = p.get("pane_id"), p.get("workspace_id")
    if not pid:
        continue
    report("pane", pid, (("pbr", ""), ("pbr_on", ""), ("pgit", ""), ("pgit_on", "")))
    c = cwd_of(p)
    base = ws_cwd.get(w, "")
    # Compared on the worktree ROOT, not the cwd string - a subdirectory of the same tree is not another checkout.
    tree = (ident(c) if c and os.path.isdir(c) else ("", ""))[0]
    btree = (ident(base) if base and os.path.isdir(base) else ("", ""))[0]
    if tree and tree != btree:
        picker[tree] = sign(tree)[2]

hg.update(picker)
PY
}

ensure_daemon() {
  mkdir -p "$STATE_DIR"
  # macOS ships no flock, so the lock check below is a silent no-op there and every kick
  # used to leave ANOTHER permanent poller behind (N pollers = N x the gitmux load). Ask
  # the process table first: portable, and the --kick args never match the --loop pattern.
  pgrep -f "$LOOP_RE" >/dev/null 2>&1 && return 0
  if command -v flock >/dev/null 2>&1; then
    # If the lock is already held, a daemon is running — nothing to do.
    if ! ( exec 9>"$LOCK"; flock -n 9 ) 2>/dev/null; then
      return 0
    fi
  fi
  if command -v setsid >/dev/null 2>&1; then
    setsid "$0" --loop >/dev/null 2>&1 &
  else
    nohup "$0" --loop >/dev/null 2>&1 &
  fi
}

run_loop() {
  mkdir -p "$STATE_DIR"
  if command -v flock >/dev/null 2>&1; then
    exec 9>"$LOCK"
    # BLOCK until we own the lock (don't exit). Under the systemd service with
    # Restart=always this makes a second instance a hot standby rather than an
    # exit-0/restart spin: if a layout-kick daemon (macOS, or a boot-race) holds
    # the lock, we wait and seamlessly take over the moment it dies.
    flock 9
  else
    # No flock (macOS): last one wins, so a raced kick can never leave two pollers
    # polling in parallel. Backstop for the pgrep check in ensure_daemon, and kept off
    # the flock path so systemd's hot-standby semantics above are untouched.
    for pid in $(pgrep -f "$LOOP_RE" 2>/dev/null); do
      [ "$pid" = "$$" ] || kill "$pid" 2>/dev/null
    done
  fi
  # Exit when the herdr socket is gone (server down): the systemd .path unit
  # (herdr-git-status.path) restarts us when it reappears, so we don't poll a dead
  # socket. A restarted server is otherwise picked up automatically (each pass
  # re-queries via the CLI). Socket path matches the daemon default; HERDR_SOCKET_PATH
  # overrides it when set.
  local sock="${HERDR_SOCKET_PATH:-$HOME/.config/herdr/herdr.sock}"
  while :; do
    [ -S "$sock" ] || exit 0
    refresh_once
    sleep "$INTERVAL"
  done
}

case "${1:-}" in
  --loop) run_loop ;;
  --kick) refresh_once; ensure_daemon ;;
  *)      refresh_once ;;
esac
