#!/usr/bin/env bash
# herdr-git-status.sh — feed each open herdr workspace's working-tree status to the
# sidebar `$git` token, using the SAME gitmux.yml as the tmux status line + the
# ctrl+t picker. herdr's built-in `git_status` token carries no working-tree signs - it
# renders only ahead/behind from herdr's internal model (src/ui/sidebar.rs formats "↑2 ↓1";
# neither number reaches `herdr api schema`, which is what the old note here mistook for the
# token being empty). This poller supplies the dirty glyph via
# `herdr workspace report-metadata --token git=…`.
# The `$git` row is wired in dot_config/herdr/config.toml ([ui.sidebar.spaces]).
#
# The same pass also writes the ctrl+t picker's status cache (herdr_gitmux.update),
# so the picker's column and this sidebar token come from ONE gitmux run per repo and
# can't disagree. Without it the picker showed whatever its last open had computed,
# i.e. arbitrarily stale; now open workspaces are at most $INTERVAL seconds behind.
#
#   herdr-git-status.sh          one refresh pass over every open workspace
#   herdr-git-status.sh --loop   daemon: refresh every $INTERVAL s (flock = one only)
#   herdr-git-status.sh --kick   refresh once now, then ensure the --loop daemon is up
#
# Everything runs through the herdr CLI (socket API), so it works local AND over
# `herdr --remote` — the poller lives on whichever host runs the herdr server, the
# same host the repos live on. gitmux SYMBOLS only (its branch field is dropped - it carries a
# glyph and its own coloring, and `$br` below asks git directly); tmux "#[…]" color codes are
# stripped since a metadata token renders as plain theme-colored text.
#
# The same pass feeds `$br`/`$br_on`, the sidebar's second row. These REPLACE herdr's built-in
# `branch` token, which can only render the branch verbatim: a ticket worktree already spells
# its key out on row 1, so row 2 carries the branch with that key stripped
# (IHRWEB-24314-listen-endpoint -> listen-endpoint). Two tokens rather than one because a
# custom token takes a single unconditional fg, losing the mauve/overlay0 focus split the
# built-in gets for free (skills/herdr-upgrade/watchlist.md item 2). Exactly one of the pair
# ever holds the text: herdr-focus-tracker.py::paint_branch moves it on workspace.focused, and
# this pass picks the same slot from `focused` so an 8s poll never drags the accent back.
set -uo pipefail

herdr="${HERDR_BIN_PATH:-herdr}"
. "$HOME/.local/bin/mux/shared/mux-env.sh"
export HERDR_BIN_PATH="$herdr"

GITMUX_CFG="$HOME/.config/gitmux/gitmux.yml"
SCRIPTS_DIR="$HOME/.local/bin/mux/herdr"
INTERVAL="${HERDR_GIT_INTERVAL:-8}"
export TTL_MS=$(( (INTERVAL + 30) * 1000 ))   # outlive a couple of missed passes
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/herdr"
LOCK="$STATE_DIR/git-status.lock"
# Bracketed first char: the regex text itself never contains the string it matches, so a
# shell whose command line mentions this pattern (an admin typing pgrep/pkill, a wrapper)
# can never be matched — and killed — as if it were the daemon.
LOOP_RE="[h]erdr-git-status[.]sh --loop"

refresh_once() {
  command -v jq >/dev/null 2>&1 || return 0
  command -v python3 >/dev/null 2>&1 || return 0
  command -v gitmux >/dev/null 2>&1 || return 0
  GITMUX_CFG="$GITMUX_CFG" SCRIPTS_DIR="$SCRIPTS_DIR" python3 - <<'PY'
import os, json, re, subprocess, sys, time

sys.dont_write_bytecode = True             # no __pycache__ in the deployed scripts dir
sys.path.insert(0, os.environ.get("SCRIPTS_DIR", os.path.expanduser("~/.local/bin/mux/herdr")))
try:
    import herdr_gitmux as hg              # shared with herdr-sesh.sh — see its docstring
except Exception:
    sys.exit(0)                            # mid-apply window; the next pass picks it up

HERDR = os.environ.get("HERDR_BIN_PATH", "herdr")
# Kept in step with gitmux.yml (generated by colorscheme-set). ● staged, ✖ conflict,
# ✚ modified, 󱀶 untracked. NOT the stash or the insertion/deletion glyphs.
DIRTY_SIGNS = ("●", "✖", "✚", "\U000f1036")
# ✚ over ● on purpose: ● is already the sidebar's agent state_icon, and reusing it for
# "repo is dirty" would read as a second status dot on the same panel.
DIRTY_GLYPH = "✚"
CFG = os.environ.get("GITMUX_CFG", os.path.expanduser("~/.config/gitmux/gitmux.yml"))
TTL = os.environ.get("TTL_MS", "60000")
seq = str(time.time_ns())                  # ns: monotonic, and above any manual probe seq

def out(args, cwd=None):
    try:
        return subprocess.run(args, cwd=cwd, capture_output=True, text=True, timeout=4).stdout
    except Exception:
        return ""

# Ticket key stripped off the front, because row 1 of the sidebar already ends in it
# (herdr-sesh-layout.sh labels a bucketed ticket worktree web/infra/IHRWEB-24314). master,
# untick/foo and every other unprefixed branch pass through whole. Detached HEAD has no branch
# name, so it falls back to the short sha rather than leaving the row blank.
TICKET_PREFIX = re.compile(r"^[A-Z]+-[0-9]+-")

def branch(cwd):
    name = out(["git", "-C", cwd, "branch", "--show-current"]).strip()
    if not name:
        return out(["git", "-C", cwd, "rev-parse", "--short", "HEAD"]).strip()
    return TICKET_PREFIX.sub("", name) or name

try:
    panes = json.loads(out([HERDR, "pane", "list"]))
except Exception:
    sys.exit(0)

# Which space is active decides whether the branch goes in `$br` (dim) or `$br_on` (accent).
# The swap itself is herdr-focus-tracker.py's job, event-driven off workspace.focused; this
# pass only has to agree with it, or every poll would drag the accent back to the wrong space.
try:
    focused = {w["workspace_id"] for w in
               json.loads(out([HERDR, "workspace", "list"]))["result"]["workspaces"]
               if w.get("focused")}
except Exception:
    focused = set()

ws_cwd = {}
for p in panes.get("result", {}).get("panes", []):
    w = p.get("workspace_id")
    c = (p.get("foreground_cwd") or p.get("cwd") or "").rstrip("/")
    if w and c and w not in ws_cwd:
        ws_cwd[w] = c

now = time.time()
picker = {}
for w, c in ws_cwd.items():
    if not os.path.isdir(c):
        continue
    _branch, spairs = hg.parse(hg.run(c, CFG))          # branch dropped: herdr shows it already
    # Sidebar token is ONE glyph: "this tree has uncommitted work", nothing more. The full
    # per-class counts stay in the ctrl+t picker and the tmux status line, which have the
    # width for them; a 26-col sidebar does not, and the counts were never actionable there.
    # DIRTY_SIGNS is the gitmux staged/conflict/modified/untracked set — stash is deliberately
    # excluded (stashed work is not uncommitted work in the tree), as are the insertion and
    # deletion line counts. Clean tree clears the token, so the row disappears entirely.
    sym = DIRTY_GLYPH if any(s in hg.plain(spairs) for s in DIRTY_SIGNS) else ""
    # Same gitmux run feeds the ctrl+t picker's cache, so its column can't disagree
    # with this token. roots_only is moot here: a workspace cwd is asked either way.
    picker[c] = hg.entry(spairs, now)
    # ONE call for all three tokens, not one per token: a second report from the same --source
    # carrying the same --seq is dropped as not-newer, so split calls silently lost whichever
    # went second. --token and --clear-token are both repeatable and mix freely.
    args = [HERDR, "workspace", "report-metadata", w, "--source", "gitmux", "--seq", seq,
            "--ttl-ms", TTL]
    br = branch(c)
    lit = w in focused
    for name, value in (("git", sym), ("br", "" if lit else br), ("br_on", br if lit else "")):
        args += ["--token", name + "=" + value] if value else ["--clear-token", name]
    subprocess.run(args, capture_output=True)

hg.update(picker)
PY
}

ensure_daemon() {
  mkdir -p "$STATE_DIR"
  # macOS ships no flock, so the lock check below is a silent no-op there and every kick
  # used to leave ANOTHER permanent poller behind (N pollers = N x the gitmux load). Ask
  # the process table first: portable, and the --kick args never match the --loop pattern.
  pgrep -f "$LOOP_RE" >/dev/null 2>&1 && return 0
  if command -v flock >/dev/null 2>&1; then
    # If the lock is already held, a daemon is running — nothing to do.
    if ! ( exec 9>"$LOCK"; flock -n 9 ) 2>/dev/null; then
      return 0
    fi
  fi
  if command -v setsid >/dev/null 2>&1; then
    setsid "$0" --loop >/dev/null 2>&1 &
  else
    nohup "$0" --loop >/dev/null 2>&1 &
  fi
}

run_loop() {
  mkdir -p "$STATE_DIR"
  if command -v flock >/dev/null 2>&1; then
    exec 9>"$LOCK"
    # BLOCK until we own the lock (don't exit). Under the systemd service with
    # Restart=always this makes a second instance a hot standby rather than an
    # exit-0/restart spin: if a layout-kick daemon (macOS, or a boot-race) holds
    # the lock, we wait and seamlessly take over the moment it dies.
    flock 9
  else
    # No flock (macOS): last one wins, so a raced kick can never leave two pollers
    # polling in parallel. Backstop for the pgrep check in ensure_daemon, and kept off
    # the flock path so systemd's hot-standby semantics above are untouched.
    for pid in $(pgrep -f "$LOOP_RE" 2>/dev/null); do
      [ "$pid" = "$$" ] || kill "$pid" 2>/dev/null
    done
  fi
  # Exit when the herdr socket is gone (server down): the systemd .path unit
  # (herdr-git-status.path) restarts us when it reappears, so we don't poll a dead
  # socket. A restarted server is otherwise picked up automatically (each pass
  # re-queries via the CLI). Socket path matches the daemon default; HERDR_SOCKET_PATH
  # overrides it when set.
  local sock="${HERDR_SOCKET_PATH:-$HOME/.config/herdr/herdr.sock}"
  while :; do
    [ -S "$sock" ] || exit 0
    refresh_once
    sleep "$INTERVAL"
  done
}

case "${1:-}" in
  --loop) run_loop ;;
  --kick) refresh_once; ensure_daemon ;;
  *)      refresh_once ;;
esac
